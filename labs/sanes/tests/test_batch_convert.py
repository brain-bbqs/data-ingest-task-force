"""Tests of the batch driver's own logic: session discovery, skip and overwrite, and failure reporting.

``build_nwb`` is stubbed out here. ``test_converter.py`` runs it for real.

Test functions take their arguments positionally by pytest's injection rules, so the repository's
keyword-only and positional-only conventions do not apply to them.
"""

import subprocess
import sys
from pathlib import Path

import pytest

CODE = Path(__file__).resolve().parents[1] / "code"
sys.path.insert(0, str(CODE))

import batch_convert  # noqa: E402

pytestmark = pytest.mark.ai_generated


def _make_session(path, /):
    (path / "idx_0").mkdir(parents=True)
    return path


@pytest.mark.parametrize("nesting", ["", "ssa_gt_data"])
def test_discover_sessions_at_either_depth(tmp_path, nesting):
    for name in ("experiment_281", "experiment_280"):
        _make_session(tmp_path / nesting / name)
    (tmp_path / "notes").mkdir()
    sessions, ignored = batch_convert.discover_sessions(tmp_path)
    actual = ([path.name for path in sessions], [path.name for path in ignored])
    assert actual == (["experiment_280", "experiment_281"], ["notes"])


def test_missing_input_finds_nothing(tmp_path):
    actual = batch_convert.convert_batch(
        incoming_dir=tmp_path / "missing", standardized_dir=tmp_path / "out", config_path=CODE / "config_ssa_gt.yaml"
    )
    assert actual == 0


@pytest.fixture
def recorded_calls(monkeypatch):
    calls = []

    def fake_build_nwb(*, session_dir, output_dir, config_path):
        calls.append((session_dir.name, output_dir))
        if session_dir.name == "experiment_bad":
            raise ValueError("unreadable")
        return output_dir

    monkeypatch.setattr(batch_convert, "build_nwb", fake_build_nwb)
    return calls


@pytest.mark.parametrize(
    ("overwrite", "expected"), [(False, ["experiment_new"]), (True, ["experiment_done", "experiment_new"])]
)
def test_existing_output_is_skipped_without_overwrite(tmp_path, recorded_calls, overwrite, expected):
    for name in ("experiment_done", "experiment_new"):
        _make_session(tmp_path / "in" / name)
    done = tmp_path / "out" / "autogenerated" / "sub-multi" / "sub-multi_ses-experimentdone_behavior.nwb"
    done.parent.mkdir(parents=True)
    done.touch()
    batch_convert.convert_batch(
        incoming_dir=tmp_path / "in",
        standardized_dir=tmp_path / "out",
        config_path=CODE / "config.yaml",
        overwrite=overwrite,
    )
    actual = [name for name, _ in recorded_calls]
    assert actual == expected
    assert {output_dir for _, output_dir in recorded_calls} == {tmp_path / "out" / "autogenerated"}


def test_failed_session_does_not_stop_the_batch(tmp_path, recorded_calls):
    for name in ("experiment_bad", "experiment_good"):
        _make_session(tmp_path / "in" / name)
    actual = batch_convert.convert_batch(
        incoming_dir=tmp_path / "in", standardized_dir=tmp_path / "out", config_path=CODE / "config_ssa_gt.yaml"
    )
    assert (actual, [name for name, _ in recorded_calls]) == (1, ["experiment_bad", "experiment_good"])


@pytest.mark.parametrize("flag", ["--input", "--output", "--config", "--overwrite"])
def test_cli_help(flag):
    completed = subprocess.run(
        [sys.executable, str(CODE / "batch_convert.py"), "--help"], capture_output=True, text=True, check=True
    )
    assert flag in completed.stdout
