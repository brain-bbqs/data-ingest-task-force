def test_multisubject_file(request, fixture, root, session, identifier, start, description, subjects):
    path = request.getfixturevalue(fixture) / root / "sub-multi" / f"sub-multi_ses-{session}_behavior.nwb"
    with pynwb.NWBHDF5IO(path, "r") as io:
        nwbfile = io.read()
        assert nwbfile.identifier == identifier
        assert nwbfile.session_start_time.isoformat() == start
        assert nwbfile.session_description == description

        audio = nwbfile.acquisition["Multi-channel Acoustic Data"]
        assert audio.data.shape == (sum(synthetic.CHUNK_SAMPLES), synthetic.CHANNELS)
        assert audio.rate == synthetic.AUDIO_RATE
        assert audio.data[synthetic.CHUNK_SAMPLES[0], 1] == pytest.approx(1.1)

        video = nwbfile.acquisition["External Behavioral Video (Combined)"]
        assert list(video.external_file[:]) == [f"sub-multi_ses-{session}_video.mp4"]
        assert video.rate == synthetic.VIDEO_RATE

        assert list(nwbfile.processing["behavior"].data_interfaces) == ["vocalizations"]
        events = nwbfile.processing["behavior"]["vocalizations"].to_dataframe()
        assert events["timestamp"].tolist() == pytest.approx([0.1, 0.6])
        assert events["duration"].tolist() == pytest.approx([0.05, 0.05])
        assert events["label"].tolist() == ["chirp", "chirp"]

        table = nwbfile.subjects_table.to_dataframe()
        assert table["subject_id"].tolist() == subjects
        links = table["individual_subj_link"].tolist()
        assert links == [f"../sub-{subject}/sub-{subject}_ses-{session}.nwb" for subject in subjects]
        assert all((path.parent / link).is_file() for link in links)

    with h5py.File(path, "r") as file:
        assert file["acquisition/Multi-channel Acoustic Data/data"].compression == "gzip"


