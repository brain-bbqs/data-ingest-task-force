def _convert(*, root, config_name, **session_kwargs):
    incoming = root / "incoming"
    synthetic.write_session(root=incoming, **session_kwargs)
    standardized = root / "standardized"
    exit_code = batch_convert.convert_batch(
        incoming_dir=incoming, standardized_dir=standardized, config_path=CODE / config_name
    )
    assert exit_code == 0
    return standardized


def _relative_files(root, /):
    files = sorted(str(path.relative_to(root)) for path in root.rglob("*") if path.is_file())
    return files


