def _drop_from_second_chunk(*, session, pattern):
    for path in (session / "idx_001").glob(pattern):
        path.unlink()


@pytest.mark.ai_generated
@pytest.mark.parametrize(
    ("session_kwargs", "pattern", "match"),
    [
        ({}, "*.wav", "Audio is missing"),
        ({}, "*.mp4", "Video is missing"),
        ({"video": False}, None, "needs the chunk video"),
        ({"log": False}, None, "no experiment log"),
        ({"audio": False, "video": False}, None, "No audio or video"),
    ],
)
def test_unconvertible_session(tmp_path, session_kwargs, pattern, match):
    session = synthetic.write_session(root=tmp_path / "incoming", name="experiment_150", **session_kwargs)
    if pattern is not None:
        _drop_from_second_chunk(session=session, pattern=pattern)
    with pytest.raises(ValueError, match=match):
        converter.build_nwb(
            session_dir=session, output_dir=tmp_path / "out", config_path=CODE / "config_big_arena_2024_12.yaml"
        )
    assert not list((tmp_path / "out").rglob("*.tmp"))


